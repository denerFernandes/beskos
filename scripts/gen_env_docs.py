#!/usr/bin/env python3
"""Generates docs/configuration.md from every os.Getenv / getenv call in the backend.

The table it writes is a complete, mechanically-extracted list of names and defaults --
descriptions are not attempted here (they would drift the moment someone reworded a Go comment
without touching this script). Run it after adding or removing an environment variable, and
commit the regenerated file; check_docs.py does not currently verify this file is fresh, so
review the diff by eye.

    python3 scripts/gen_env_docs.py
"""
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "configuration.md"

PATTERN = re.compile(
    r'\bos\.Getenv\("([A-Z0-9_]+)"\)'
    r'|\bgetenv(?:Int64)?\("([A-Z0-9_]+)"\s*,\s*("(?:[^"\\]|\\.)*"|[A-Za-z0-9_.<<]+)\)'
)


def scan() -> dict[str, str | None]:
    files = subprocess.run(
        ["git", "ls-files", "backend/*.go", "backend/**/*.go"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout.splitlines()
    found: dict[str, str | None] = {}
    for rel in files:
        if rel.endswith("_test.go"):
            continue
        text = (ROOT / rel).read_text(encoding="utf-8", errors="ignore")
        for m in PATTERN.finditer(text):
            if m.group(1):
                found.setdefault(m.group(1), None)
            else:
                name, default = m.group(2), m.group(3)
                default = default.strip('"') if default.startswith('"') else default
                if name not in found or found[name] is None:
                    found[name] = default or None
    return found


# Read only by the operator console (backend/cmd/manager-api, backend/internal/managerapi),
# which isn't part of this build -- listing them here would document a feature that isn't there.
MANAGER_ONLY_PREFIX = "MANAGER_"
MANAGER_ONLY_NAMES = {"APP_PUBLIC_URL"}  # doesn't carry the prefix, but is manager-api only


def render(vars_: dict[str, str | None]) -> str:
    vars_ = {
        name: default for name, default in vars_.items()
        if not name.startswith(MANAGER_ONLY_PREFIX) and name not in MANAGER_ONLY_NAMES
    }
    lines = [
        "<!-- Generated by scripts/gen_env_docs.py -- edit the Go source, not this file. -->",
        "",
        "# Configuration",
        "",
        "Every environment variable the backend reads, extracted directly from the source so "
        "this list cannot silently drift. A variable with no default is required for the "
        "feature it belongs to; most of them are optional and simply turn a feature off when "
        "unset (see the log line the server prints at startup for which).",
        "",
        "| Variable | Default |",
        "|---|---|",
    ]
    for name in sorted(vars_):
        default = vars_[name]
        cell = f"`{default}`" if default not in (None, "") else "*(required or empty = off)*"
        lines.append(f"| `{name}` | {cell} |")
    lines.append("")
    lines.append(
        "See [docs/getting-started.md](getting-started.md) for the minimum set to start "
        "developing, and [docs/self-hosting.md](self-hosting.md) for a production checklist."
    )
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render(scan()))
    print(f"wrote {OUT.relative_to(ROOT)}")
