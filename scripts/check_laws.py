#!/usr/bin/env python3
"""Mechanical check for the project laws in CLAUDE.md.

Why this exists: the laws were written down and still broken, twice in one day, by an agent that
had just finished fixing the same violation. A document does not enforce anything -- it only tells
you what you should have done, after you did not. This runs.

What it checks, on ADDED lines only (compared to git HEAD):

  1. Language (law 4.6) -- code, comments, logs and error strings must be English.
  2. File size (law 1.4) -- 600 lines maximum.

ADDED LINES ONLY is the whole design. The repository still holds thousands of Portuguese comments
from before the rule changed; checking whole files would report them forever and the check would be
switched off within a day. Checking only what you just wrote makes the backlog irrelevant and the
signal exact.

Usage:
    scripts/check_laws.py                 # every file changed against HEAD (working tree)
    scripts/check_laws.py FILE [FILE...]  # specific files
    scripts/check_laws.py --base REF      # compare against REF instead of HEAD (CI)
    scripts/check_laws.py --hook          # reads a Claude Code hook payload on stdin

On CI the working tree IS the commit, so the default HEAD comparison would find nothing and the
job would pass while proving nothing. Pass --base with the branch you are merging into.

Escape hatch: a line ending in `lang:ok` is skipped. It is for the one legitimate case -- product
copy shown to end users in Portuguese (SMS text, pt-BR fallbacks). Anything else, fix the line.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

MAX_LINES = 600

# Files whose Portuguese content is the product, not the code.
SKIP_PARTS = (
    "/locales/",           # i18n dictionaries: Portuguese is the point
    "/node_modules/",
    "/internal/db/",       # generated by sqlc (law 1.4 exempts it)
    "/dist/",
    "/.next/",
    "/public/mediapipe/",
    "/public/ort/",
    "/public/models/",
)
SKIP_SUFFIX = (".md", ".json", ".lock", ".sum", ".svg", ".png", ".webp", ".ico")

CODE_SUFFIX = (".go", ".ts", ".tsx", ".js", ".jsx", ".sql", ".py", ".sh", ".rs", ".yml", ".yaml")

# Portuguese letters that simply do not occur in English words.
ACCENTS = re.compile(r"[áàâãéêíóôõúüçÁÀÂÃÉÊÍÓÔÕÚÇ]")

# Portuguese words that are NOT also English words. Every entry here was checked against English:
# "no", "do", "as", "os", "em", "se", "era", "ate", "data", "some", "one", "a", "e", "o" are
# deliberately absent: they are real English words and would fire on correct code.
WORDS = r"""
nao|que|para|uma|umas|uns|dos|das|pelo|pela|pelos|pelas|isso|isto|aqui|ali|quando|porque|porquê|
mesmo|mesma|ainda|cada|onde|tambem|sempre|nunca|depois|antes|entao|assim|apenas|quase|muito|muita|
pouco|pouca|todos|todas|toda|algum|alguma|alguns|nenhum|nenhuma|qualquer|desde|embora|enquanto|
precisa|precisam|fica|ficam|ficar|faz|fazem|fazer|vai|vao|tem|tinha|teve|ter|ser|sendo|foi|foram|
seria|deve|devem|devia|pode|podem|podia|sabe|sabem|saber|chave|chaves|nome|nomes|corpo|erro|erros|
balde|caminho|tamanho|ficheiro|ficheiros|arquivo|arquivos|pasta|pastas|senha|senhas|utilizador|
usuario|usuarios|mensagem|mensagens|aviso|avisos|dados|valores|linha|linhas|lista|listas|
tela|janela|janelas|botao|botoes|entrada|saida|inicio|fim|meio|cima|baixo|dentro|fora|junto|
sobre|sob|entre|contra|conforme|segundo|primeiro|primeira|ultimo|ultima|novo|nova|novos|novas|
velho|velha|antigo|antiga|grande|pequeno|pequena|melhor|pior|certo|certa|errado|errada|
vazio|vazia|cheio|cheia|aberto|aberta|fechado|fechada|ligado|ligada|desligado|desligada|
soma|conta|contas|numero|numeros|hora|horas|dia|dias|semana|ano|anos|
sem|com|por|mais|menos|muito|tudo|nada|alguem|ninguem|outro|outra|outros|outras
"""
WORDS_RE = re.compile(r"\b(" + WORDS.replace("\n", "").strip("|") + r")\b", re.IGNORECASE)

# -cao/-coes/-dade endings: the give-away Portuguese suffixes, even unaccented.
SUFFIX_RE = re.compile(r"\b\w+(?:cao|coes|acao|acoes|dade|mente)\b", re.IGNORECASE)

ALLOW = re.compile(r"lang:ok\s*$")


def is_checkable(path: str) -> bool:
    p = "/" + path.replace("\\", "/")
    # This file holds the Portuguese dictionary; it is data, not prose, and cannot be translated
    # without deleting the check itself. Everything else in it was written in English by hand.
    if p.endswith("/check_laws.py"):
        return False
    if any(part in p for part in SKIP_PARTS):
        return False
    if path.endswith(SKIP_SUFFIX):
        return False
    return path.endswith(CODE_SUFFIX)


def git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True, check=False).stdout
    except OSError:
        return ""


def added_lines(path: str, base: str = "HEAD") -> list[tuple[int, str]]:
    """Lines this tree adds to `base`. A file git does not know about is entirely new."""
    tracked = git("ls-files", "--error-unmatch", path).strip()
    if not tracked:
        try:
            return list(enumerate(Path(path).read_text(errors="replace").splitlines(), 1))
        except OSError:
            return []

    out, lineno, result = git("diff", "-U0", base, "--", path), 0, []
    for raw in out.splitlines():
        if raw.startswith("@@"):
            m = re.search(r"\+(\d+)", raw)
            lineno = int(m.group(1)) if m else 0
            continue
        if raw.startswith("+") and not raw.startswith("+++"):
            result.append((lineno, raw[1:]))
            lineno += 1
    return result


def portuguese_in(line: str) -> str | None:
    """The first Portuguese marker in the line, or None. Ignores URLs and import paths, which are
    identifiers of other people's things and not ours to rename."""
    if ALLOW.search(line):
        return None
    stripped = re.sub(r"https?://\S+", "", line)
    # Domain names end in ".com"/".org": the \b in WORDS would read that as Portuguese "com".
    stripped = re.sub(r"\b[\w-]+\.(?:com|org|net|io|br|pt|dev|app)\b", "", stripped)
    stripped = re.sub(r"""(?:import|from|require)\s*\(?\s*["'][^"']+["']""", "", stripped)
    for probe in (ACCENTS, SUFFIX_RE, WORDS_RE):
        m = probe.search(stripped)
        if m:
            return m.group(0)
    return None


def check(paths: list[str], base: str = "HEAD") -> list[str]:
    problems: list[str] = []
    for path in paths:
        if not is_checkable(path):
            continue
        try:
            total = len(Path(path).read_text(errors="replace").splitlines())
        except OSError:
            continue
        if total > MAX_LINES:
            problems.append(
                f"{path}: {total} lines, the limit is {MAX_LINES} (law 1.4). "
                f"Split it by responsibility."
            )
        for lineno, text in added_lines(path, base):
            found = portuguese_in(text)
            if found:
                problems.append(
                    f"{path}:{lineno}: Portuguese in new code -- {found!r} (law 4.6). "
                    f"Code, comments and log/error strings are English.\n    {text.strip()[:100]}"
                )
    return problems


def main() -> int:
    args = sys.argv[1:]
    base = "HEAD"
    if "--base" in args:
        i = args.index("--base")
        base = args[i + 1] if i + 1 < len(args) else "HEAD"
        del args[i:i + 2]

    if "--hook" in args:
        try:
            payload = json.load(sys.stdin)
        except (json.JSONDecodeError, ValueError):
            return 0
        path = (payload.get("tool_input") or {}).get("file_path")
        paths = [path] if path else []
    elif [a for a in args if not a.startswith("--")]:
        paths = [a for a in args if not a.startswith("--")]
    else:
        paths = [p for p in git("diff", "--name-only", base).split() if p]
        paths += [p for p in git("ls-files", "--others", "--exclude-standard").split() if p]

    problems = check(paths, base)
    if not problems:
        return 0
    print("LAW VIOLATION (CLAUDE.md) -- fix before continuing:\n", file=sys.stderr)
    for p in problems:
        print("  " + p, file=sys.stderr)
    # 2 is the exit code Claude Code feeds back to the agent as a blocking error.
    return 2


if __name__ == "__main__":
    sys.exit(main())
